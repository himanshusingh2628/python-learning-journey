# Python Data Types

# String
name = "Himanshu"

# Integer
age = 20

# Float
percentage = 85.5

# Boolean
is_student = True

# List
skills = ["Python", "SQL", "Power BI"]

# Dictionary
student = {
    "name": "Himanshu",
    "course": "B.Tech CSE"
}

print("Name:", name)
print("Age:", age)
print("Percentage:", percentage)
print("Is Student:", is_student)
print("Skills:", skills)
print("Student:", student)

# Display data types
print("\nData Types:")
print(type(name))
print(type(age))
print(type(percentage))
print(type(is_student))
print(type(skills))
print(type(student))
